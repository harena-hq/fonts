"""Write the package's stylesheets, npm/ui.css, npm/j.css, npm/icons.css and npm/index.css, which
imports the first and the last, from the built fonts, build_web's files and the weight ranges Edge
gives Segoe (data/v0_2/matching.json). The tracked copies must equal what this writes.

Each face is declared under its installed family name, upright; Harena UI's and the icons' with their
files' code points as their `unicode-range`. A Harena UI J face is Harena UI's file for Harena UI's
code points, then its chunks, each declared over the blocks its code points are in
(build_web.declared). The most common chunks are declared last, to be checked first. No face
overrides its line metrics: a line is Segoe's height whatever it holds, as in WinUI (v0.6.1).

A text face asks for kerning in its own descriptor (`font-feature-settings: "kern" 1`): Firefox's
`font-kerning: auto` otherwise drops it for CJK and under `ko` and `ja`, which Edge does not (1.0
item 6). Kerning is what Blink applies under `auto` already, and a page's `font-kerning: none` still
overrides a descriptor (CSS Fonts 4, 7.2).

Usage: python scripts/build_css.py [--check]
"""
import json
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build import ROOT, SIZES, WEIGHTS, face_path  # noqa: E402
from build_j import face_path_j  # noqa: E402
from build_web import ICONS, chunks, declared, j_file, ui_file  # noqa: E402

NPM = ROOT / "npm"
HEADER = "/* Generated by scripts/build_css.py from the built fonts; do not edit. */\n"


def weight_ranges():
    """{weight: (low, high)}: the CSS weights Edge draws each Segoe instance for, the same in each size."""
    sizes = json.loads((ROOT / "data/v0_2/matching.json").read_text())["sizes"]
    steps = {tuple(map(tuple, v["dom_weights"])) for v in sizes.values()}
    assert len(steps) == 1, "optical sizes match weights differently"
    steps = sorted(steps.pop())
    out = {}
    for i, (low, w) in enumerate(steps):
        out[w] = (low, steps[i + 1][0] - 1 if i + 1 < len(steps) else 1000)
    assert set(out) == set(WEIGHTS), out
    return out


def unicode_range(points):
    points, spans = sorted(points), []
    for c in points:
        if spans and c == spans[-1][1] + 1:
            spans[-1][1] = c
        else:
            spans.append([c, c])
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in spans)


def face(family, file, weight, points, kern=True):
    lines = [f'  font-family: "{family}";',
             f'  src: url("./fonts/{file}") format("woff2");',
             f"  font-weight: {weight};",
             "  font-style: normal;",
             "  font-display: block;"]
    if kern:
        lines.append('  font-feature-settings: "kern" 1;')
    lines.append(f"  unicode-range: {unicode_range(points)};")
    return "@font-face {\n" + "\n".join(lines) + "\n}\n"


def stylesheets():
    ranges = weight_ranges()
    ui, j = [HEADER], [HEADER]
    for size in SIZES:
        for w in WEIGHTS:
            span = "{} {}".format(*ranges[w])
            ui_cmap = TTFont(face_path(size, w), lazy=True).getBestCmap()
            ui.append(face(f"Harena UI {size}", ui_file(size, w), span, ui_cmap))
            j.append(face(f"Harena UI J {size}", ui_file(size, w), span, ui_cmap))
            j_cmap = TTFont(face_path_j(size, w), lazy=True).getBestCmap()
            for name, points in chunks(j_cmap, ui_cmap).items():
                j.append(face(f"Harena UI J {size}", j_file(size, w, name), span, declared(name, points)))
    # One face, as Segoe Fluent Icons has: a bolder request is synthesized for both alike.
    icons = [HEADER, face("Harena UI Icons", "HarenaUIIcons-Regular.woff2", "400",
                          TTFont(ICONS, lazy=True).getBestCmap(), kern=False)]
    index = HEADER + '@import "./ui.css";\n@import "./icons.css";\n'
    return {"index.css": index, "ui.css": "\n".join(ui), "j.css": "\n".join(j), "icons.css": "\n".join(icons)}


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in stylesheets().items():
        path = NPM / name
        if check:
            if not path.is_file() or path.read_text() != text:
                stale.append(name)
        else:
            NPM.mkdir(exist_ok=True)
            path.write_text(text)
            print(name, len(text))
    if stale:
        print("stylesheets differ from what build_css.py writes:", *stale, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
