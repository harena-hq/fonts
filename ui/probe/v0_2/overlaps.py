"""Write data/v0_2/overlaps.json, the gate's allow-list per face, from the current build.

Each entry says how far the glyph's ink crosses its advance (min sidebearing, px
at 1000 px) in Harena UI, in Open Sans at its own advance, and in Segoe.
"design": Open Sans itself crosses by more than 2 px and Harena UI by no more
than 5 px further, so the overhang is the typeface's. "induced": the rest, where
Segoe's narrower advance makes or deepens it.

The list is regenerated, never hand-edited; a change to it is reviewed as a diff.

Usage: python probe/v0_2/overlaps.py   (after scripts/build.py)
"""
import json
import sys
import unicodedata
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import build as B  # noqa: E402


def face(size, w, point):
    target, seg = B.segoe(size, w)
    built = TTFont(B.face_path(size, w))
    ref = B.instance(B.OPEN_SANS, point["wght"], point["wdth"])
    bc, rc = built.getBestCmap(), ref.getBestCmap()
    entries = []
    for cp in B.overlaps(built, target, seg):
        bx, ox = B.ink_x(built, bc[cp]), B.ink_x(ref, rc[cp])
        ours = min(bx[0], built["hmtx"][bc[cp]][0] - bx[1]) / B.PX
        own = min(ox[0], ref["hmtx"][rc[cp]][0] - ox[1]) / B.PX
        s = seg["ink"][str(cp)]
        theirs = min(s[0], seg["advance"][str(cp)] - s[1])
        entries.append({"cp": cp, "char": chr(cp), "name": unicodedata.name(chr(cp), ""),
                        "kind": "design" if own < -2 and ours >= own - 5 else "induced",
                        "harena": round(ours, 1), "open_sans": round(own, 1), "segoe": round(theirs, 1)})
    return {"code_points": [e["cp"] for e in entries], "entries": entries}


def main():
    points = json.loads((ROOT / "data/v0_2/build.json").read_text())
    faces = {}
    for size, w in B.FACES:
        name = B.face_name(size, w)
        faces[name] = face(size, w, points[name])
        kinds = [e["kind"] for e in faces[name]["entries"]]
        print(f"{name}: {len(kinds)} overlaps, {kinds.count('design')} design, "
              f"{kinds.count('induced')} induced")
    doc = {"about": "Per face, glyphs whose ink crosses the advance by more than 5 px at 1000 px "
                    "beyond Segoe's own glyph. Generated by probe/v0_2/overlaps.py; see its docstring.",
           "faces": faces}
    (ROOT / "data/v0_2/overlaps.json").write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
